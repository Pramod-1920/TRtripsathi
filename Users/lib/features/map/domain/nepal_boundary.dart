bool isInsideNepal(LatLng point) {
  var inside = false;
  for (var index = 0, previous = nepalBoundary.length - 1;
      index < nepalBoundary.length;
      previous = index++) {
    final currentPoint = nepalBoundary[index];
    final previousPoint = nepalBoundary[previous];
    final crossesLatitude = (currentPoint.latitude > point.latitude) !=
        (previousPoint.latitude > point.latitude);
    if (!crossesLatitude) continue;
    final boundaryLongitude =
        (previousPoint.longitude - currentPoint.longitude) *
                (point.latitude - currentPoint.latitude) /
                (previousPoint.latitude - currentPoint.latitude) +
            currentPoint.longitude;
    if (point.longitude < boundaryLongitude) inside = !inside;
  }
  return inside;
}
